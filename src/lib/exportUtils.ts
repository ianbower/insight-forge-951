import pptxgen from "pptxgenjs";
import jsPDF from "jspdf";
import html2canvas from "html2canvas";

export interface StickyNoteData {
  id: string;
  content: string;
  color: string;
  position: { x: number; y: number };
  section?: string;
}

export interface CanvasExportData {
  title: string;
  sections: {
    name: string;
    notes: StickyNoteData[];
  }[];
}

export async function exportToPPT(data: CanvasExportData) {
  const pptx = new pptxgen();
  pptx.title = data.title;
  pptx.author = "Consulting Workbench";

  // Title slide
  const titleSlide = pptx.addSlide();
  titleSlide.addText(data.title, {
    x: 0.5,
    y: 2,
    w: "90%",
    h: 1.5,
    fontSize: 44,
    bold: true,
    color: "1a365d",
    align: "center",
  });
  titleSlide.addText("Generated by Consulting Workbench", {
    x: 0.5,
    y: 4,
    w: "90%",
    fontSize: 18,
    color: "666666",
    align: "center",
  });

  // Content slide for each section
  data.sections.forEach((section) => {
    const slide = pptx.addSlide();
    
    // Section title
    slide.addText(section.name, {
      x: 0.5,
      y: 0.3,
      w: "90%",
      h: 0.6,
      fontSize: 28,
      bold: true,
      color: "1a365d",
    });

    // Add notes as bullet points
    const bulletPoints = section.notes.map((note) => ({
      text: note.content || "(empty)",
      options: { bullet: true, indentLevel: 0 },
    }));

    if (bulletPoints.length > 0) {
      slide.addText(bulletPoints, {
        x: 0.5,
        y: 1.2,
        w: "90%",
        h: 4,
        fontSize: 14,
        color: "333333",
        valign: "top",
      });
    } else {
      slide.addText("No items added to this section", {
        x: 0.5,
        y: 1.2,
        w: "90%",
        fontSize: 14,
        color: "999999",
        italic: true,
      });
    }
  });

  // Save the file
  await pptx.writeFile({ fileName: `${data.title.replace(/\s+/g, "_")}.pptx` });
}

export async function exportToPDF(elementId: string, title: string) {
  const element = document.getElementById(elementId);
  if (!element) {
    throw new Error("Element not found");
  }

  const canvas = await html2canvas(element, {
    scale: 2,
    backgroundColor: "#ffffff",
    logging: false,
  });

  const imgData = canvas.toDataURL("image/png");
  const pdf = new jsPDF({
    orientation: "landscape",
    unit: "mm",
  });

  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  
  // Add title
  pdf.setFontSize(24);
  pdf.setTextColor(26, 54, 93);
  pdf.text(title, 10, 15);

  // Calculate image dimensions to fit page
  const imgWidth = pageWidth - 20;
  const imgHeight = (canvas.height * imgWidth) / canvas.width;
  
  // Add the canvas image
  pdf.addImage(imgData, "PNG", 10, 25, imgWidth, Math.min(imgHeight, pageHeight - 35));

  // Add footer
  pdf.setFontSize(10);
  pdf.setTextColor(128, 128, 128);
  pdf.text(`Generated by Consulting Workbench - ${new Date().toLocaleDateString()}`, 10, pageHeight - 5);

  pdf.save(`${title.replace(/\s+/g, "_")}.pdf`);
}

export async function exportDocumentationToPDF(elementId: string, title: string) {
  const element = document.getElementById(elementId);
  if (!element) {
    throw new Error("Element not found");
  }

  // Capture at higher scale for quality
  const canvas = await html2canvas(element, {
    scale: 2,
    backgroundColor: "#ffffff",
    logging: false,
    useCORS: true,
    allowTaint: true,
  });

  const imgData = canvas.toDataURL("image/png");
  
  // Use portrait orientation for documentation
  const pdf = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  const margin = 10;
  const contentWidth = pageWidth - (margin * 2);
  const headerHeight = 15;
  const footerHeight = 10;
  const contentAreaHeight = pageHeight - headerHeight - footerHeight - (margin * 2);

  // Calculate scaled image dimensions
  const imgWidth = contentWidth;
  const imgHeight = (canvas.height * imgWidth) / canvas.width;

  // Calculate number of pages needed
  const totalPages = Math.ceil(imgHeight / contentAreaHeight);

  for (let page = 0; page < totalPages; page++) {
    if (page > 0) {
      pdf.addPage();
    }

    // Add header
    pdf.setFontSize(10);
    pdf.setTextColor(26, 54, 93);
    pdf.text(title, margin, margin + 5);
    
    // Add page number
    pdf.setFontSize(9);
    pdf.setTextColor(128, 128, 128);
    pdf.text(`Page ${page + 1} of ${totalPages}`, pageWidth - margin - 25, margin + 5);

    // Calculate the portion of image to show on this page
    const sourceY = page * contentAreaHeight * (canvas.width / contentWidth);
    const sourceHeight = Math.min(
      contentAreaHeight * (canvas.width / contentWidth),
      canvas.height - sourceY
    );
    
    // Create a temporary canvas for this page's portion
    const tempCanvas = document.createElement("canvas");
    tempCanvas.width = canvas.width;
    tempCanvas.height = sourceHeight;
    const tempCtx = tempCanvas.getContext("2d");
    
    if (tempCtx) {
      tempCtx.fillStyle = "#ffffff";
      tempCtx.fillRect(0, 0, tempCanvas.width, tempCanvas.height);
      tempCtx.drawImage(
        canvas,
        0, sourceY, canvas.width, sourceHeight,
        0, 0, canvas.width, sourceHeight
      );
      
      const pageImgData = tempCanvas.toDataURL("image/png");
      const pageImgHeight = (sourceHeight * contentWidth) / canvas.width;
      
      pdf.addImage(
        pageImgData,
        "PNG",
        margin,
        headerHeight + margin,
        contentWidth,
        pageImgHeight
      );
    }

    // Add footer
    pdf.setFontSize(8);
    pdf.setTextColor(128, 128, 128);
    pdf.text(
      `aXet Consult Platform Documentation • Generated ${new Date().toLocaleDateString()}`,
      margin,
      pageHeight - margin
    );
  }

  pdf.save(`${title.replace(/\s+/g, "_")}.pdf`);
}
